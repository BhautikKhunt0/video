async def one(i,start,text):
    c=edge_tts.Communicate(text,VOICE,rate='-3%',boundary='WordBoundary')
    words=[];audio=bytearray()
    async for ch in c.stream():
        if ch['type']=='audio': audio+=ch['data']
        elif ch['type']=='WordBoundary':
            words.append({'w':ch['text'],'t':round(ch['offset']/1e7,3),'d':round(ch['duration']/1e7,3)})
    open(f'src/assets/vo/{i:02d}.mp3','wb').write(audio)
    dur=words[-1]['t']+words[-1]['d'] if words else 0
    return {'i':i,'start':start,'text':text,'words':words,'dur':round(dur,3)}
async def main():
    res=[]
    for i,(s,t) in enumerate(LINES):
        for a in range(4):
            try:
                res.append(await one(i,s,t)); break
            except Exception as e:
                print("retry",i,e); await asyncio.sleep(1.5)
    for r in res: print(r['i'],r['start'],'->',round(r['start']+r['dur'],2),'(+0.2 tail)', r['text'][:40])
    for a,b in zip(res,res[1:]):
        if a['start']+a['dur']+0.15>b['start']: print('OVERLAP',a['i'],b['i'])
    ts="// AUTO-GENERATED by scripts/gen_vo.py\n"
    ts+=''.join(f"import vo{r['i']} from './vo/{r['i']:02d}.mp3';\n" for r in res)
    ts+="export interface VoWord{w:string;t:number;d:number}\nexport interface VoLine{i:number;start:number;text:string;words:VoWord[];dur:number;url:string}\n"
    ts+="export const VO:VoLine[]=["
    for r in res: ts+=json.dumps({**r})[:-1]+f",\"url\":__URL{r['i']}__}},\n"
    ts+="];\n"
    for r in res: ts=ts.replace(f'"__URL{r["i"]}__"',f"vo{r['i']}").replace(f"__URL{r['i']}__",f"vo{r['i']}")
    open('src/assets/voData.ts','w').write(ts)
asyncio.run(main())
